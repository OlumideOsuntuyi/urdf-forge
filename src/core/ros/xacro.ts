/** One xacro that emits any supported target: `xacro robot.urdf.xacro sim:=jazzy-harmonic`. */
import { hasJoint, orderedLinks, safeName, type RobotModel } from "../model";
import { fmt } from "../math";
import { TARGETS, type TargetId } from "./targets";
import {
  GENERATOR,
  controlXml,
  gazeboLinkXml,
  jointStateXml,
  jointXml,
  linkXml,
  materialsXml,
  xmlEscape,
} from "./urdf";

const indent = (s: string, by = "  ") => by + s.replace(/\n/g, `\n${by}`);

export function generateXacro(
  model: RobotModel,
  targets: TargetId[],
  defaultTarget: TargetId,
): string {
  const o = ['<?xml version="1.0"?>'];
  o.push(`<!-- ${xmlEscape(model.robot)}: generated by ${GENERATOR}.`);
  o.push(`     xacro ${model.robot}.urdf.xacro sim:=<target>   targets: ${targets.join(", ")} -->`);
  o.push(
    `<robot name="${safeName(model.robot, "robot")}" xmlns:xacro="http://www.ros.org/wiki/xacro">`,
  );
  o.push(`  <xacro:arg name="sim" default="${defaultTarget}"/>`);
  o.push('  <xacro:property name="sim" value="$(arg sim)"/>');
  o.push(
    `  <xacro:property name="mesh_prefix" value="package://${model.packageName}/${model.meshDir}"/>`,
  );
  for (const L of orderedLinks(model))
    o.push(
      `  <xacro:property name="${safeName(L.name)}_mass" value="${fmt(Math.max(L.inertial.mass, 1e-6))}"/>`,
    );
  o.push("");
  o.push(...materialsXml(model));
  o.push("");
  const prefix = `package://${model.packageName}/${model.meshDir}/`;
  for (const L of orderedLinks(model)) {
    o.push(
      linkXml(model, L, `\${${safeName(L.name)}_mass}`)
        .split(prefix)
        .join("${mesh_prefix}/"),
    );
    if (hasJoint(model, L)) o.push(jointXml(model, L));
    o.push("");
  }
  for (const id of targets) {
    const T = TARGETS[id];
    o.push(`  <xacro:if value="\${sim == '${id}'}">`);
    for (const L of orderedLinks(model)) o.push(indent(gazeboLinkXml(model, L, T)));
    for (const block of [controlXml(model, T), jointStateXml(model, T)])
      if (block) o.push(indent(block));
    o.push("  </xacro:if>");
  }
  o.push("</robot>");
  return o.join("\n") + "\n";
}
