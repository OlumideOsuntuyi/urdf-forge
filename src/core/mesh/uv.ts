/**
 * Texture coordinates for meshes that have none (STL, generated parts): box projection. Each
 * triangle is projected onto the plane facing its normal's dominant axis, in metres, so a
 * texture with a 1 m tile repeats every metre on every side of the part.
 */

/** UVs (2 per vertex) for a triangle soup, in metres. Divide by the tile size to texture. */
export function boxUVs(positions: ArrayLike<number>): Float32Array {
  const n = Math.floor(positions.length / 9);
  const uv = new Float32Array(n * 6);
  for (let t = 0; t < n; t++) {
    const b = t * 9;
    const ux = positions[b + 3] - positions[b],
      uy = positions[b + 4] - positions[b + 1],
      uz = positions[b + 5] - positions[b + 2];
    const vx = positions[b + 6] - positions[b],
      vy = positions[b + 7] - positions[b + 1],
      vz = positions[b + 8] - positions[b + 2];
    const nx = Math.abs(uy * vz - uz * vy),
      ny = Math.abs(uz * vx - ux * vz),
      nz = Math.abs(ux * vy - uy * vx);
    // Project onto the plane most facing the triangle: (y,z) for X-facing, (x,z) for Y, (x,y) for Z.
    const [a, c] = nx >= ny && nx >= nz ? [1, 2] : ny >= nz ? [0, 2] : [0, 1];
    for (let k = 0; k < 3; k++) {
      uv[t * 6 + k * 2] = positions[b + k * 3 + a];
      uv[t * 6 + k * 2 + 1] = positions[b + k * 3 + c];
    }
  }
  return uv;
}

/** Wavefront OBJ with box-projected UVs (scaled by 1/tile) and flat normals. */
export function writeObj(positions: Float32Array, tile = 1, name = "mesh"): string {
  const uv = boxUVs(positions);
  const n = Math.floor(positions.length / 9);
  const out: string[] = [
    `# ${name}: generated by URDF Forge (box-projected UVs, tile ${tile} m)`,
    `o ${name.replace(/\s+/g, "_")}`,
  ];
  const f = (v: number) => (Math.abs(v) < 1e-9 ? "0" : v.toFixed(6).replace(/\.?0+$/, ""));
  for (let i = 0; i < n * 3; i++)
    out.push(`v ${f(positions[i * 3])} ${f(positions[i * 3 + 1])} ${f(positions[i * 3 + 2])}`);
  for (let i = 0; i < n * 3; i++) out.push(`vt ${f(uv[i * 2] / tile)} ${f(uv[i * 2 + 1] / tile)}`);
  for (let t = 0; t < n; t++) {
    const b = t * 9;
    const ux = positions[b + 3] - positions[b],
      uy = positions[b + 4] - positions[b + 1],
      uz = positions[b + 5] - positions[b + 2];
    const vx = positions[b + 6] - positions[b],
      vy = positions[b + 7] - positions[b + 1],
      vz = positions[b + 8] - positions[b + 2];
    let nx = uy * vz - uz * vy,
      ny = uz * vx - ux * vz,
      nz = ux * vy - uy * vx;
    const l = Math.hypot(nx, ny, nz) || 1;
    nx /= l;
    ny /= l;
    nz /= l;
    out.push(`vn ${f(nx)} ${f(ny)} ${f(nz)}`);
  }
  for (let t = 0; t < n; t++) {
    const i = t * 3 + 1;
    out.push(`f ${i}/${i}/${t + 1} ${i + 1}/${i + 1}/${t + 1} ${i + 2}/${i + 2}/${t + 1}`);
  }
  return out.join("\n") + "\n";
}
