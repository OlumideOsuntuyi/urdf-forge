type RobotSpec = Omit<Sample, "kind" | "source" | "complexity"> & {
  urdf: string;
  packages?: Record<string, string>;
  complexity?: Sample["complexity"];
};

const robot = (r: RobotSpec): Sample => ({
  ...r,
  kind: "robot",
  complexity: r.complexity ?? "moderate",
  source: { kind: "urdf", urdf: r.urdf, packages: r.packages ?? {} },
});

/** example-robot-data: meshes are referenced as package://example-robot-data/robots/<pkg>/... */
const erd = (
  r: Omit<RobotSpec, "packages" | "urdf" | "homepage"> & {
    path: string;
    pkg: string;
    upstream: string;
  },
): Sample =>
  robot({
    ...r,
    urdf: `${ERD}/${r.path}`,
    packages: { "example-robot-data": ERD, [r.pkg]: `${ERD}/robots/${r.pkg}` },
    homepage: r.upstream,
    attribution: `${r.attribution}, via Gepetto/example-robot-data`,
  });

const unitree = (
  id: string,
  name: string,
  path: string,
  pkg: string,
  sizeMB: number,
  category: string,
  description: string,
  complexity: Sample["complexity"] = "complex",
): Sample =>
  robot({
    id,
    name,
    category,
    description,
    complexity,
    urdf: `${UNITREE}/${path}`,
    packages: { [pkg]: `${UNITREE}/robots/${pkg}` },
    license: "BSD-3-Clause",
    permissive: true,
    attribution: "Unitree Robotics",
    homepage: "https://github.com/unitreerobotics/unitree_ros",
    sizeMB,
  });

