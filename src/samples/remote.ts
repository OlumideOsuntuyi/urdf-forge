const fuel = (
  id: string,
  name: string,
  asset: string,
  type: "model" | "world",
  category: string,
  description: string,
  complexity: Sample["complexity"],
  license: string,
  sizeMB: number,
): Sample => ({
  id: `env.${id}`,
  kind: "environment",
  name,
  category,
  description,
  complexity,
  source: {
    kind: "fuel",
    url: `https://fuel.gazebosim.org/1.0/OpenRobotics/${type}s/${encodeURIComponent(asset)}`,
    type,
  },
  license,
  permissive: true,
  attribution: "Open Robotics, Gazebo Fuel",
  homepage: `https://app.gazebosim.org/OpenRobotics/fuel/${type}s/${encodeURIComponent(asset)}`,
  sizeMB,
});

const aws = (
  id: string,
  name: string,
  repo: string,
  sha: string,
  world: string,
  description: string,
  sizeMB: number,
  complexity: Sample["complexity"] = "complex",
): Sample => {
  const base = gh(`aws-robotics/aws-robomaker-${repo}`, sha);
  return {
    id: `env.${id}`,
    kind: "environment",
    name,
    category: "AWS RoboMaker worlds",
    description,
    complexity,
    source: { kind: "sdf", sdf: `${base}/${world}`, modelsBase: `${base}/models` },
    license: "MIT-0",
    permissive: true,
    attribution: "Amazon.com, Inc. or its affiliates",
    homepage: `https://github.com/aws-robotics/aws-robomaker-${repo}`,
    sizeMB,
  };
};

